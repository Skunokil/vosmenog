#!/usr/bin/env bash
# ПОРОГ СМЕНЫ — что агент видит на входе, в любом проекте.
#
# Заведён 2026-09-12 по решению владельца. Повод: за сутки в одном рабочем
# дереве столкнулись три сессии — пять раз, и ни одно столкновение не было
# небрежностью: агент просто не знал, что рядом кто-то есть. Узнавать это
# должна машина на входе, а не человек по следам.
#
# Скрипт ничего не запрещает. Он показывает обстановку и называет следующий
# шаг. Решение принимает сессия, согласует — владелец.
#
# Три обстановки, три разных совета:
#   один в дереве          — оркестратор не нужен, согласовывай с владельцем;
#   несколько, без оркестратора — объяви область и предложи поднять оркестратора;
#   несколько, с оркестратором  — доложись ему, релизы через него.
#
# Надпроектный: лежит в ~/.claude/hooks/, работает в любом каталоге. Вне
# git-репозитория молчит про ветку и файлы, но про соседей говорит всегда.
set -uo pipefail

ORCH="$HOME/.claude/hooks/orchestrator.sh"

echo "── Порог смены ─────────────────────────────────────────────"

# 0. Часы. Сервер живёт по UTC, владелец — по Москве (+3), и это расходится
#    не только на часы, но и на дату около полуночи. 2026-09-18: сессия весь
#    разговор говорила «вечер» и «доброй ночи», когда у владельца было 11:39
#    утра — метки времени в выводе Confluence (14:07 MSK) лежали на экране
#    и не были сложены с временем сервера. Поэтому время печатается первым.
echo "  Сейчас: $(LC_TIME=ru_RU.UTF-8 TZ=Europe/Moscow date '+%H:%M %d.%m.%Y, %A') — по Москве, время владельца"
echo "          $(date '+%H:%M') UTC на сервере. Разница +3; про время суток"
echo "          говорить по московскому, а не по серверному."

# 1. Живые сессии. Сокет считается живым, только если его процесс на месте:
#    мёртвые сессии оставляют сокеты, и без проверки счёт врёт.
socks="/run/user/$(id -u)/cc-socks"
alive=0
neighbours=""

# Свой pid — ближайший предок с именем claude, чтобы не показать себя соседом.
me_pid=""
_p=$PPID
for _ in $(seq 1 12); do
  [[ -z "$_p" || "$_p" == "1" ]] && break
  _n="$(ps -o comm= -p "$_p" 2>/dev/null | tr -d ' ')"
  [[ "$_n" == *claude* ]] && { me_pid="$_p"; break; }
  _p="$(ps -o ppid= -p "$_p" 2>/dev/null | tr -d ' ')"
done

if [[ -d "$socks" ]]; then
  for s in "$socks"/*.sock; do
    [[ -e "$s" ]] || continue
    pid="$(basename "$s" .sock)"
    kill -0 "$pid" 2>/dev/null || continue
    alive=$((alive + 1))
    [[ "$pid" == "$me_pid" ]] && continue
    # Где искать окно: терминал, возраст, каталог. Добавлено 2026-09-12 по
    # просьбе владельца — порог говорил «рядом работают ещё сессии: 3» и не
    # говорил, ГДЕ они. tmux на машине нет, Claude Code не демон: подключиться
    # к работающей сессии снаружи нельзя, единственная зацепка — tty.
    tty="$(ps -o tty= -p "$pid" 2>/dev/null | tr -d ' ')"
    age="$(ps -o etime= -p "$pid" 2>/dev/null | tr -d ' ')"
    cwd="$(readlink -f /proc/$pid/cwd 2>/dev/null | sed "s|$HOME|~|")"
    neighbours+="      pid $pid · ${tty:-без tty} · $age · ${cwd:-?}"$'\n'
  done
fi
# Себя вычитаем, только если мы под claude. Зовут хук не из Claude Code
# (evm boot из opencode или чужого агента) - me_pid пуст, и все живые сокеты
# чужие: вычитание занижало бы число соседей на одного (EPIC-026 Ф3).
if [[ -n "$me_pid" ]]; then others=$(( alive > 0 ? alive - 1 : 0 )); else others=$alive; fi

if (( others == 0 )); then
  echo "  Ты один в работе. Оркестратор не нужен:"
  echo "  согласовывай действия напрямую с владельцем."
else
  echo "  Рядом работают ещё сессии: $others"
  [[ -n "$neighbours" ]] && printf '%s' "$neighbours"
  echo "  → Окно ищется по tty: переключиться на него. Подключиться снаружи"
  echo "    нельзя (tmux нет, Claude Code не демон); потеряно окно —"
  echo "    claude --resume <id> поднимет новую сессию с той же историей."
  if orch_line=$("$ORCH" who 2>/dev/null); then
    echo "  $orch_line"
    echo "  → Доложись ему: чем занят и какие каталоги трогаешь."
    echo "    Релизы и выкаты — через него, не своей рукой."
  else
    echo "  Оркестратора нет."
    echo "  → Объяви свою область соседям: ListAgents, затем SendMessage."
    echo "  → Предложи владельцу поднять окно-оркестратор: когда сессий"
    echo "    больше одной, релиз собирать некому — каждый видит свой кусок."
    echo "    Берёт роль на себя: ~/.claude/hooks/orchestrator.sh claim"
  fi
fi

# 2. Чужая работа в дереве — самый практичный сигнал, что рядом кто-то есть.
if git rev-parse --git-dir >/dev/null 2>&1; then
  dirty="$(git status --porcelain 2>/dev/null | grep -v '^??' || true)"
  if [[ -n "$dirty" ]]; then
    n=$(echo "$dirty" | wc -l)
    echo "  В дереве незакоммиченных файлов: $n"
    echo "$dirty" | sed 's/^/      /' | head -6
    (( n > 6 )) && echo "      … и ещё $((n - 6))"
    if (( others > 0 )); then
      echo "  → Не твоё? Не коммить и не откладывай в stash: в общем дереве"
      echo "    stash снимает изменения у всех сразу."
    fi
  fi
  branch="$(git branch --show-current 2>/dev/null || echo '?')"
  tag="$(git tag --sort=-creatordate 2>/dev/null | grep -m1 '^v' || echo '—')"
  echo "  Ветка: $branch · последний тег: $tag"
fi

# Раскладка проектов (EPIC-025 vosmenog): сторож из дистрибутива, одна строка.
# Сигнал, не запрет: свои нарушения разобрать до работы, чужие — доложить.
if [[ -x "$HOME/agent-os/bin/projects-index.py" ]]; then
  layout="$(timeout 10 "$HOME/agent-os/bin/projects-index.py" --summary 2>/dev/null)"
  [[ -n "$layout" ]] && echo "  $layout"
fi

echo "────────────────────────────────────────────────────────────"
exit 0
